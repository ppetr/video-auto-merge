"""End-to-end alignment of two video files.

`AlignVideos` extracts (or reuses cached) per-frame signatures of both
videos, aligns them with `frame_dp_align.AlignFrames` and returns the
result together with the frame timestamps needed to interpret it.
"""
import asyncio
import dataclasses
import logging
import pathlib
from typing import List

import numpy as np
import numpy.typing as npt

from video_auto_merge import frame_dp_align
from video_auto_merge import signatures

DEFAULT_PRE_INPUT_ARGS = ('-hwaccel', 'cuda')


@dataclasses.dataclass
class VideoAlignment:
  """Result of `AlignVideos`: the alignment of the left and right videos,
  plus each video's per-frame timestamps in seconds (indexed like the
  frame indices in `result`)."""
  left_times: npt.ArrayLike
  right_times: npt.ArrayLike
  result: frame_dp_align.FrameAlignmentResult


async def _EnsureSignatures(ffmpeg_path: pathlib.PurePath,
                            videos: List[pathlib.Path], cache_dir: pathlib.Path,
                            pre_input_args: List[str]) -> List[pathlib.Path]:
  xml_paths = [signatures.SignatureCachePath(cache_dir, v) for v in videos]
  await asyncio.gather(*[
      signatures.EnsureSignature(ffmpeg_path, video, xml_path, pre_input_args)
      for video, xml_path in zip(videos, xml_paths)
  ])
  return xml_paths


def AlignVideos(
    left_video: pathlib.PurePath,
    right_video: pathlib.PurePath,
    cache_dir: pathlib.PurePath,
    params: frame_dp_align.FrameDpParams = frame_dp_align.FrameDpParams(),
    ffmpeg_path: pathlib.PurePath = pathlib.PurePath('ffmpeg'),
    pre_input_args: List[str] = DEFAULT_PRE_INPUT_ARGS,
) -> VideoAlignment:
  """Aligns two videos at frame resolution.

  Signatures are generated by ffmpeg (both videos concurrently - the slow,
  CPU-bound step) into `cache_dir` and reused on later runs for as long as
  the video file is not newer than its cached signature. `pre_input_args`
  go before each ffmpeg `-i`, by default hardware-accelerated decoding.
  """
  left_video = pathlib.Path(left_video)
  right_video = pathlib.Path(right_video)
  left_xml, right_xml = asyncio.run(
      _EnsureSignatures(ffmpeg_path, [left_video, right_video],
                        pathlib.Path(cache_dir), list(pre_input_args)))
  left_times, left_sigs, _ = signatures.LoadSignatures(left_xml)
  right_times, right_sigs, _ = signatures.LoadSignatures(right_xml)
  logging.info('Aligning %d x %d frames (can take a long time on a GPU)',
               len(left_times), len(right_times))
  result = frame_dp_align.AlignFrames(left_sigs, right_sigs, params)
  return VideoAlignment(np.asarray(left_times), np.asarray(right_times), result)
